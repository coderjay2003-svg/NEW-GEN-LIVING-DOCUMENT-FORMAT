/**
 * LDOC Studio Universal Exporter Engine
 * Provides 100% client-side, zero-backend export of living documents to:
 * 1. Microsoft Word (.docx) via OpenXML generator
 * 2. Microsoft PowerPoint (.pptx) presentation slides
 * 3. Standalone self-contained single-file HTML (.html)
 * 4. High-fidelity publication PDF (via native vector print engine)
 */
(function (global) {
  'use strict';

  function xmlEscape(str) {
    if (!str) return '';
    return String(str)
      .replace(/&/g, '&amp;')
      .replace(/</g, '&lt;')
      .replace(/>/g, '&gt;')
      .replace(/"/g, '&quot;')
      .replace(/'/g, '&apos;');
  }

  function sanitizeFilename(name) {
    return (name || 'document').replace(/[^a-zA-Z0-9_\-]/g, '_');
  }

  const LDocExportEngine = {
    /**
     * 1. Export Document AST to native Microsoft Word (.docx)
     */
    exportToDocx: async function (spec) {
      if (typeof JSZip === 'undefined') {
        throw new Error('JSZip library required for client-side DOCX export');
      }
      const title = spec.title || 'Living Document';
      const pages = spec.pages || [];
      const zip = new JSZip();

      // [Content_Types].xml
      zip.file('[Content_Types].xml', `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">
  <Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/>
  <Default Extension="xml" ContentType="application/xml"/>
  <Override PartName="/word/document.xml" ContentType="application/vnd.openxmlformats-officedocument.wordprocessingml.document.main+xml"/>
  <Override PartName="/word/styles.xml" ContentType="application/vnd.openxmlformats-officedocument.wordprocessingml.styles+xml"/>
</Types>`);

      // _rels/.rels
      zip.file('_rels/.rels', `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">
  <Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="word/document.xml"/>
</Relationships>`);

      // word/_rels/document.xml.rels
      zip.file('word/_rels/document.xml.rels', `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">
  <Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/styles" Target="styles.xml"/>
</Relationships>`);

      // word/styles.xml
      zip.file('word/styles.xml', `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<w:styles xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main">
  <w:style w:type="paragraph" w:default="1" w:styleId="Normal">
    <w:name w:val="Normal"/>
    <w:rPr>
      <w:rFonts w:ascii="Calibri" w:hAnsi="Calibri"/>
      <w:sz w:val="22"/>
      <w:color w:val="222222"/>
    </w:rPr>
  </w:style>
  <w:style w:type="paragraph" w:styleId="Heading1">
    <w:name w:val="heading 1"/>
    <w:rPr>
      <w:b/>
      <w:sz w:val="36"/>
      <w:color w:val="1E293B"/>
    </w:rPr>
  </w:style>
  <w:style w:type="paragraph" w:styleId="Heading2">
    <w:name w:val="heading 2"/>
    <w:rPr>
      <w:b/>
      <w:sz w:val="28"/>
      <w:color w:val="334155"/>
    </w:rPr>
  </w:style>
  <w:style w:type="paragraph" w:styleId="Heading3">
    <w:name w:val="heading 3"/>
    <w:rPr>
      <w:b/>
      <w:sz w:val="24"/>
      <w:color w:val="475569"/>
    </w:rPr>
  </w:style>
</w:styles>`);

      // Generate document.xml body from pages and blocks
      let docXmlBody = '';
      // Document title header
      docXmlBody += `<w:p>
        <w:pPr><w:pStyle w:val="Heading1"/><w:jc w:val="center"/></w:pPr>
        <w:r><w:rPr><w:b/><w:sz w:val="44"/><w:color w:val="0F172A"/></w:rPr><w:t>${xmlEscape(title)}</w:t></w:r>
      </w:p>`;
      docXmlBody += `<w:p><w:pPr><w:jc w:val="center"/></w:pPr><w:r><w:rPr><w:color w:val="64748B"/><w:sz w:val="20"/></w:rPr><w:t>Generated by LDOC Studio • Living Document Suite</w:t></w:r></w:p>`;
      docXmlBody += `<w:p/>`;

      pages.forEach((page, pIdx) => {
        if (pIdx > 0) {
          docXmlBody += `<w:p><w:r><w:br w:type="page"/></w:r></w:p>`;
        }
        if (page.title) {
          docXmlBody += `<w:p><w:pPr><w:pStyle w:val="Heading2"/></w:pPr><w:r><w:t>${xmlEscape(page.title)}</w:t></w:r></w:p>`;
        }

        const blocks = page.blocks || [];
        blocks.forEach(block => {
          const bType = (block.type || '').toLowerCase();
          const text = block.content || block.text || '';

          if (bType === 'heading') {
            const lvl = block.level || 1;
            const styleId = lvl === 1 ? 'Heading1' : (lvl === 2 ? 'Heading2' : 'Heading3');
            docXmlBody += `<w:p><w:pPr><w:pStyle w:val="${styleId}"/></w:pPr><w:r><w:t>${xmlEscape(text)}</w:t></w:r></w:p>`;
          } else if (bType === 'paragraph' || bType === 'text') {
            docXmlBody += `<w:p><w:r><w:t>${xmlEscape(text)}</w:t></w:r></w:p>`;
          } else if (bType === 'list') {
            const items = Array.isArray(block.items) ? block.items : [text];
            items.forEach(item => {
              docXmlBody += `<w:p><w:pPr><w:ind w:left="720"/></w:pPr><w:r><w:rPr><w:b/></w:rPr><w:t>• </w:t></w:r><w:r><w:t>${xmlEscape(typeof item === 'object' ? item.text || JSON.stringify(item) : item)}</w:t></w:r></w:p>`;
            });
          } else if (bType === 'quote' || bType === 'callout') {
            docXmlBody += `<w:p><w:pPr><w:ind w:left="720"/><w:jc w:val="both"/></w:pPr><w:r><w:rPr><w:i/><w:color w:val="475569"/></w:rPr><w:t>"${xmlEscape(text)}"</w:t></w:r></w:p>`;
          } else if (bType === 'code') {
            const codeLines = (text || '').split('\n');
            codeLines.forEach(line => {
              docXmlBody += `<w:p><w:pPr><w:shd w:val="clear" w:color="auto" w:fill="F1F5F9"/></w:pPr><w:r><w:rPr><w:rFonts w:ascii="Consolas" w:hAnsi="Consolas"/><w:sz w:val="19"/><w:color w:val="0F172A"/></w:rPr><w:t xml:space="preserve">${xmlEscape(line)}</w:t></w:r></w:p>`;
            });
          } else if (bType === 'table') {
            const headers = block.headers || [];
            const rows = block.rows || [];
            if (headers.length > 0 || rows.length > 0) {
              docXmlBody += `<w:tbl>
                <w:tblPr>
                  <w:tblW w:w="5000" w:type="pct"/>
                  <w:tblBorders>
                    <w:top w:val="single" w:sz="4" w:space="0" w:color="CBD5E1"/>
                    <w:left w:val="single" w:sz="4" w:space="0" w:color="CBD5E1"/>
                    <w:bottom w:val="single" w:sz="4" w:space="0" w:color="CBD5E1"/>
                    <w:right w:val="single" w:sz="4" w:space="0" w:color="CBD5E1"/>
                    <w:insideH w:val="single" w:sz="4" w:space="0" w:color="E2E8F0"/>
                    <w:insideV w:val="single" w:sz="4" w:space="0" w:color="E2E8F0"/>
                  </w:tblBorders>
                </w:tblPr>`;
              if (headers.length > 0) {
                docXmlBody += `<w:tr><w:trPr><w:tblHeader/></w:trPr>`;
                headers.forEach(h => {
                  docXmlBody += `<w:tc><w:tcPr><w:shd w:val="clear" w:color="auto" w:fill="E2E8F0"/></w:tcPr><w:p><w:r><w:rPr><w:b/></w:rPr><w:t>${xmlEscape(h)}</w:t></w:r></w:p></w:tc>`;
                });
                docXmlBody += `</w:tr>`;
              }
              rows.forEach(row => {
                const cells = Array.isArray(row) ? row : Object.values(row);
                docXmlBody += `<w:tr>`;
                cells.forEach(c => {
                  docXmlBody += `<w:tc><w:p><w:r><w:t>${xmlEscape(c)}</w:t></w:r></w:p></w:tc>`;
                });
                docXmlBody += `</w:tr>`;
              });
              docXmlBody += `</w:tbl><w:p/>`;
            }
          } else if (text) {
            docXmlBody += `<w:p><w:r><w:t>${xmlEscape(text)}</w:t></w:r></w:p>`;
          }
        });
      });

      const documentXml = `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<w:document xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main">
  <w:body>
    ${docXmlBody}
    <w:sectPr>
      <w:pgSz w:w="12240" w:h="15840"/>
      <w:pgMar w:top="1440" w:right="1440" w:bottom="1440" w:left="1440"/>
    </w:sectPr>
  </w:body>
</w:document>`;

      zip.file('word/document.xml', documentXml);

      const blob = await zip.generateAsync({ type: 'blob', mimeType: 'application/vnd.openxmlformats-officedocument.wordprocessingml.document' });
      const filename = sanitizeFilename(title) + '.docx';
      LDocExportEngine._triggerDownload(blob, filename);
      return filename;
    },

    /**
     * 2. Export Document Pages to native PowerPoint Slides (.pptx)
     */
    exportToPptx: async function (spec) {
      if (typeof JSZip === 'undefined') {
        throw new Error('JSZip library required for client-side PPTX export');
      }
      const title = spec.title || 'Presentation';
      const pages = spec.pages || [{ title: 'Slide 1', blocks: [] }];
      const zip = new JSZip();

      let ctOverrides = '';
      pages.forEach((_, idx) => {
        ctOverrides += `\n  <Override PartName="/ppt/slides/slide${idx + 1}.xml" ContentType="application/vnd.openxmlformats-officedocument.presentationml.slide+xml"/>`;
      });

      zip.file('[Content_Types].xml', `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">
  <Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/>
  <Default Extension="xml" ContentType="application/xml"/>
  <Override PartName="/ppt/presentation.xml" ContentType="application/vnd.openxmlformats-officedocument.presentationml.presentation.main+xml"/>${ctOverrides}
</Types>`);

      zip.file('_rels/.rels', `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">
  <Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="ppt/presentation.xml"/>
</Relationships>`);

      let presRels = '';
      pages.forEach((_, idx) => {
        presRels += `\n  <Relationship Id="rId${idx + 1}" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/slide" Target="slides/slide${idx + 1}.xml"/>`;
      });
      zip.file('ppt/_rels/presentation.xml.rels', `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">${presRels}
</Relationships>`);

      let sldIdLst = '';
      pages.forEach((_, idx) => {
        sldIdLst += `\n    <p:sldId id="${256 + idx}" r:id="rId${idx + 1}"/>`;
      });
      zip.file('ppt/presentation.xml', `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<p:presentation xmlns:p="http://schemas.openxmlformats.org/presentationml/2006/main" xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships">
  <p:sldMasterIdLst/>
  <p:sldIdLst>${sldIdLst}
  </p:sldIdLst>
  <p:sldSz cx="9144000" cy="5143500"/>
  <p:notesSz cx="6858000" cy="9144000"/>
</p:presentation>`);

      pages.forEach((page, idx) => {
        let shapesXml = '';
        const slideTitle = page.title || (idx === 0 ? title : `Slide ${idx + 1}`);

        shapesXml += `<p:sp>
          <p:nvSpPr>
            <p:cNvPr id="2" name="Title 1"/>
            <p:cNvSpPr><a:spLocks noGrp="1"/></p:cNvSpPr>
            <p:nvPr><p:ph type="ctrTitle"/></p:nvPr>
          </p:nvSpPr>
          <p:spPr>
            <a:xfrm><a:off x="685800" y="457200"/><a:ext cx="7772400" cy="1143000"/></a:xfrm>
          </p:spPr>
          <p:txBody>
            <a:bodyPr/>
            <a:p>
              <a:pPr algn="ctr"/>
              <a:r>
                <a:rPr lang="en-US" sz="3600" b="1"><a:solidFill><a:srgbClr val="0F172A"/></a:solidFill></a:rPr>
                <a:t>${xmlEscape(slideTitle)}</a:t>
              </a:r>
            </a:p>
          </p:txBody>
        </p:sp>`;

        let bodyParas = '';
        const blocks = page.blocks || [];
        blocks.forEach(block => {
          const text = block.content || block.text || '';
          if (text) {
            bodyParas += `<a:p>
              <a:r>
                <a:rPr lang="en-US" sz="1800"><a:solidFill><a:srgbClr val="334155"/></a:solidFill></a:rPr>
                <a:t>${xmlEscape(text)}</a:t>
              </a:r>
            </a:p>`;
          }
          if (block.items && Array.isArray(block.items)) {
            block.items.forEach(it => {
              const itText = typeof it === 'object' ? it.text || JSON.stringify(it) : String(it);
              bodyParas += `<a:p>
                <a:pPr lvl="1"/>
                <a:r>
                  <a:rPr lang="en-US" sz="1600"><a:solidFill><a:srgbClr val="475569"/></a:solidFill></a:rPr>
                  <a:t>• ${xmlEscape(itText)}</a:t>
                </a:r>
              </a:p>`;
            });
          }
        });

        if (!bodyParas) {
          bodyParas = `<a:p><a:r><a:rPr lang="en-US" sz="1600"/><a:t>Living Document Slide • Interactive runtime in .ldocx</a:t></a:r></a:p>`;
        }

        shapesXml += `<p:sp>
          <p:nvSpPr>
            <p:cNvPr id="3" name="Content Placeholder 2"/>
            <p:cNvSpPr><a:spLocks noGrp="1"/></p:cNvSpPr>
            <p:nvPr><p:ph idx="1"/></p:nvPr>
          </p:nvSpPr>
          <p:spPr>
            <a:xfrm><a:off x="685800" y="1828800"/><a:ext cx="7772400" cy="2857500"/></a:xfrm>
          </p:spPr>
          <p:txBody>
            <a:bodyPr/>
            ${bodyParas}
          </p:txBody>
        </p:sp>`;

        const slideXml = `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<p:sld xmlns:p="http://schemas.openxmlformats.org/presentationml/2006/main" xmlns:a="http://schemas.openxmlformats.org/drawingml/2006/main" xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships">
  <p:cSld>
    <p:spTree>
      <p:nvGrpSpPr><p:cNvPr id="1" name=""/><p:cNvGrpSpPr/><p:nvPr/></p:nvGrpSpPr>
      <p:grpSpPr><a:xfrm><a:off x="0" y="0"/><a:ext cx="0" cy="0"/><a:chOff x="0" y="0"/><a:chExt cx="0" cy="0"/></a:xfrm></p:grpSpPr>
      ${shapesXml}
    </p:spTree>
  </p:cSld>
</p:sld>`;

        zip.file(`ppt/slides/slide${idx + 1}.xml`, slideXml);
      });

      const blob = await zip.generateAsync({ type: 'blob', mimeType: 'application/vnd.openxmlformats-officedocument.presentationml.presentation' });
      const filename = sanitizeFilename(title) + '.pptx';
      LDocExportEngine._triggerDownload(blob, filename);
      return filename;
    },

    /**
     * 3. Export to Standalone Single-File Static HTML (.html)
     */
    exportToHtml: function (spec) {
      const title = spec.title || 'Living Document';
      const specJson = JSON.stringify(spec);

      const htmlContent = `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width,initial-scale=1.0">
<title>${xmlEscape(title)} - LDOC Living Presentation</title>
<style>
  :root { --bg: #07090e; --surface: #0f1420; --border: rgba(255,255,255,0.1); --text: #f1f5f9; --text-sub: #94a3b8; --gold: #f59e0b; }
  * { box-sizing: border-box; margin: 0; padding: 0; }
  body { background: var(--bg); color: var(--text); font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, sans-serif; display: flex; flex-direction: column; min-height: 100vh; }
  header { background: var(--surface); border-bottom: 1px solid var(--border); padding: 12px 24px; display: flex; justify-content: space-between; align-items: center; }
  .title { font-size: 16px; font-weight: 800; color: #fff; }
  .badge { background: linear-gradient(135deg, #f59e0b, #d97706); color: #000; font-size: 10px; font-weight: 900; padding: 2px 7px; border-radius: 4px; }
  main { flex: 1; max-width: 900px; width: 100%; margin: 24px auto; padding: 0 20px; }
  .slide { background: var(--surface); border: 1px solid var(--border); border-radius: 14px; padding: 32px; margin-bottom: 24px; box-shadow: 0 10px 30px rgba(0,0,0,0.5); }
  .slide-head { font-size: 22px; font-weight: 800; margin-bottom: 18px; color: #fff; border-bottom: 1px solid rgba(255,255,255,0.06); padding-bottom: 10px; }
  .block { margin-bottom: 14px; line-height: 1.6; font-size: 15px; color: #cbd5e1; }
  .block h1 { font-size: 26px; color: #fff; margin: 12px 0; }
  .block h2 { font-size: 20px; color: #f1f5f9; margin: 10px 0; }
  .block h3 { font-size: 17px; color: #e2e8f0; margin: 8px 0; }
  .block ul { padding-left: 24px; }
  .block li { margin-bottom: 6px; }
  .block pre { background: #05070a; border: 1px solid var(--border); padding: 14px; border-radius: 8px; font-family: monospace; font-size: 13px; overflow-x: auto; color: #38bdf8; }
  .block table { width: 100%; border-collapse: collapse; margin: 12px 0; }
  .block th, .block td { border: 1px solid var(--border); padding: 8px 12px; text-align: left; }
  .block th { background: rgba(255,255,255,0.05); color: #fff; font-weight: 700; }
  footer { text-align: center; padding: 20px; color: var(--text-sub); font-size: 12px; border-top: 1px solid var(--border); }
</style>
</head>
<body>
<header>
  <div style="display:flex;align-items:center;gap:10px">
    <span class="badge">LDOCX STATIC EMBED</span>
    <span class="title">${xmlEscape(title)}</span>
  </div>
  <div style="font-size:12px;color:var(--text-sub)">Standalone Single-File Player</div>
</header>
<main id="app-root"></main>
<footer>Generated by LDOC Studio • The Living Document Format Standard</footer>
<script>
  const doc = ${specJson};
  const root = document.getElementById('app-root');
  (doc.pages || []).forEach((page, pIdx) => {
    const s = document.createElement('div');
    s.className = 'slide';
    let h = '<div class="slide-head">' + (page.title || ('Page ' + (pIdx + 1))) + '</div>';
    (page.blocks || []).forEach(b => {
      const t = (b.type || '').toLowerCase();
      const content = b.content || b.text || '';
      if (t === 'heading') {
        h += '<div class="block"><h' + (b.level || 2) + '>' + content + '</h' + (b.level || 2) + '></div>';
      } else if (t === 'paragraph' || t === 'text') {
        h += '<div class="block"><p>' + content + '</p></div>';
      } else if (t === 'list') {
        h += '<div class="block"><ul>' + (b.items || []).map(it => '<li>' + (typeof it === 'object' ? it.text : it) + '</li>').join('') + '</ul></div>';
      } else if (t === 'code') {
        h += '<div class="block"><pre><code>' + content + '</code></pre></div>';
      } else if (content) {
        h += '<div class="block"><p>' + content + '</p></div>';
      }
    });
    s.innerHTML = h;
    root.appendChild(s);
  });
</script>
</body>
</html>`;

      const blob = new Blob([htmlContent], { type: 'text/html;charset=utf-8' });
      const filename = sanitizeFilename(title) + '.html';
      LDocExportEngine._triggerDownload(blob, filename);
      return filename;
    },

    _triggerDownload: function (blob, filename) {
      const a = document.createElement('a');
      a.href = URL.createObjectURL(blob);
      a.download = filename;
      document.body.appendChild(a);
      a.click();
      document.body.removeChild(a);
      setTimeout(() => URL.revokeObjectURL(a.href), 1500);
    }
  };

  global.LDocExportEngine = LDocExportEngine;
})(typeof window !== 'undefined' ? window : this);
